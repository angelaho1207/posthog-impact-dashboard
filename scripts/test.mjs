import assert from 'node:assert/strict';
import { titleType, tierOf, isGenerated, isStamp, areaOf, keywordMultiplier, reviewSubstance } from './classify.mjs';
assert.equal(titleType('fix(flags): stop per-flag queries'), 'fix');
assert.equal(titleType('Revert "feat: x"'), 'revert');
assert.equal(titleType('feat!: breaking'), 'feat');
assert.equal(titleType('61 fix action url not saving'), 'untyped');
assert.equal(tierOf('posthog/clickhouse/migrations/0100_x.py').w, 3.0);
assert.equal(tierOf('posthog/hogql/database/schema/events.py').w, 2.0);
assert.equal(tierOf('posthog/hogql/parser.py').w, 3.0);
assert.equal(tierOf('frontend/src/scenes/x.tsx').w, 1.2);
assert.equal(tierOf('README.md').w, 0.5);
assert.equal(tierOf('products/flags/backend/api.py').w, 2.0);
assert.ok(isGenerated('pnpm-lock.yaml') && isGenerated('posthog/hogql/database/test/__snapshots__/test_database.ambr') && isGenerated('frontend/src/queries/schema.json'));
assert.ok(!isGenerated('posthog/models/team.py'));
assert.ok(isStamp({ author: 'posthog[bot]', state: 'APPROVED', body: 'x'.repeat(200), inline: 0 }));
assert.ok(isStamp({ author: 'a', state: 'APPROVED', body: 'LGTM', inline: 0 }));
assert.ok(!isStamp({ author: 'a', state: 'APPROVED', body: 'LGTM', inline: 2 }));
assert.ok(!isStamp({ author: 'a', state: 'CHANGES_REQUESTED', body: '', inline: 0 }));
assert.equal(areaOf('products/flags/backend/x.py'), 'products/flags');
assert.equal(areaOf('frontend/src/scenes/x.tsx'), 'frontend/src/scenes');
assert.ok(keywordMultiplier('fix race condition in clickhouse migration').mult > 1.3);
assert.ok(keywordMultiplier('chore: bump deps and fix typo').mult < 0.9);
assert.ok(reviewSubstance({ body: 'What happens if the migration fails halfway?', inline: 3, state: 'CHANGES_REQUESTED' }) > reviewSubstance({ body: 'nit: typo', inline: 0, state: 'COMMENTED' }));
console.log('all classify tests pass');
